export const DISCOVER_FILTERS_COPY = Object.freeze({ tr, en, es });

/** Uygulama diline göre metin tablosu (bilinmeyen dil → İngilizce). */
export const getDiscoverFiltersCopy = (language) =>
  DISCOVER_FILTERS_COPY[copyLanguage(language, Object.keys(DISCOVER_FILTERS_COPY))];

/** "{n}" gibi yer tutucuları doldurur. */
export const fillCopy = (text, values = {}) =>
  String(text).replace(/\{(\w+)\}/g, (_, key) => (key in values ? String(values[key]) : `{${key}}`));

/** `describeFilters` (utils/discoverFilters.js) için tablo: ratingChip işleve çevrilir. */
export const describeCopyOf = (copy) => ({
  genres: copy.genres,
  eras: copy.eras,
  runtimes: copy.runtimes,
  languages: copy.languages,
  onMyPlatforms: copy.ui.onMyPlatforms,
  hideWatched: copy.ui.hideWatched,
  ratingChip: (n) => fillCopy(copy.ui.ratingChip, { n }),
});
