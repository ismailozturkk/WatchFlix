export const HAPTICS_COPY = Object.freeze({ tr, en, es, pt, de, it, fr, ja });

/** Uygulama diline göre metin tablosu (bilinmeyen dil → İngilizce). */
export const getHapticsCopy = (language) =>
  HAPTICS_COPY[copyLanguage(language, Object.keys(HAPTICS_COPY))];

/** "{level}" gibi yer tutucuları doldurur. */
export const fillHapticsCopy = (text, values = {}) =>
  String(text).replace(/\{(\w+)\}/g, (_, key) => (key in values ? String(values[key]) : `{${key}}`));

/** Ayarlar ana ekranındaki satırın alt yazısı. */
export const hapticsRowSubtitle = (copy, prefs) =>
  prefs?.enabled
    ? fillHapticsCopy(copy.rowOn, {
        level: copy.levels[prefs.level]?.[0] ?? "",
        intensity: copy.intensities[prefs.intensity] ?? "",
      })
    : copy.rowOff;
