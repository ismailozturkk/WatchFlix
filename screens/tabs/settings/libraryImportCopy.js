export const LIBRARY_IMPORT_COPY = { tr, en, es, pt, de, it, fr, ja };

// Bilinmeyen dil İngilizce (utils/appLanguages kuralı).
export const getLibraryImportCopy = (language) =>
  LIBRARY_IMPORT_COPY[copyLanguage(language, Object.keys(LIBRARY_IMPORT_COPY))];

/** Dosya hata kodu (utils/libraryImport + services/libraryImportService) → metin. */
export const fileErrorText = (copy, code) => copy.fileErrors[code] || copy.fileErrors["read-failed"];

/** Aktarım hata kodu (services/import/importErrors) → metin. */
export const runErrorText = (copy, code) => copy.runErrors[code] || copy.runErrors.generic;

/** Kesintiden sonra "Kaldığı yerden sürdür" anlamlı mı? (dosya hatası değil, aktarım kesintisi) */
export const isResumableError = (code) =>
  code === "cancelled" || code === "network" || code === "tmdbUnavailable" || code === "saveInterrupted" || code === "generic";
