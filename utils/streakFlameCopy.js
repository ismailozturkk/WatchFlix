// Bilinmeyen dil İngilizce (utils/appLanguages kuralı).
export const getStreakFlameCopy = (language) =>
  STREAK_FLAME_COPY[copyLanguage(language, Object.keys(STREAK_FLAME_COPY))];

/** Kademe metni: 47 → "1 ay 2 hafta 3 gün" (sıfır olan parçalar atlanır). */
export function streakLevelText(copy, level) {
  const parcalar = [];
  if (level?.month > 0) parcalar.push(copy.parts.month(level.month));
  if (level?.week > 0) parcalar.push(copy.parts.week(level.week));
  if (level?.day > 0 || !parcalar.length) parcalar.push(copy.parts.day(level?.day || 0));
  return parcalar.join(" ");
}
