/** Dil tablosu + kimlikten ad/açıklama kuran yardımcılar. */
export function getWatchChallengesCopy(language) {
  const table = WATCH_CHALLENGES_COPY[copyLanguage(language, Object.keys(WATCH_CHALLENGES_COPY))];
  return {
    ...table,
    titleOf: (challenge) => {
      const person = challenge?.person;
      if (!person) return table.titles[challenge?.id] || "";
      return person.role === "actor"
        ? table.actorTitle(person.name, challenge.target, person.capped)
        : table.directorTitle(person.name, challenge.target, person.capped);
    },
    descOf: (challenge) => {
      const person = challenge?.person;
      if (!person) return table.descs[challenge?.id] || "";
      return person.role === "actor"
        ? table.actorDesc(person.name, challenge.target, person.capped)
        : table.directorDesc(person.name, challenge.target, person.capped);
    },
    windowOf: (challenge) => {
      const window = challenge?.window;
      if (window?.type === "rolling") return table.windowRolling(window.days);
      if (window?.type === "month") return table.windowMonth(table.months[window.month - 1]);
      return table.windowOpen;
    },
    /** Döşemedeki kısa pencere: "30 gün" · "Bu ay" · "Süresiz". */
    windowShortOf: (challenge) => {
      const window = challenge?.window;
      if (window?.type === "rolling") return table.daysShort(window.days);
      if (window?.type === "month") return table.thisMonth;
      return table.noDeadline;
    },
  };
}
