// Bilinmeyen dil İngilizce (utils/appLanguages kuralı).
export const getBingoCopy = (language) =>
  BINGO_COPY[copyLanguage(language, Object.keys(BINGO_COPY))];

/** Bir kare için { short, long } metni (kopya tablosundan, parametreleri uygulanmış). */
export function bingoCellText(copy, cell) {
  const entry = copy.cells[cell.kind];
  if (!entry) return { short: "", long: "" };
  const arg = cell.kind === "genre" ? copy.genres[cell.genre] || cell.genre : cell.n;
  const apply = (value) => (typeof value === "function" ? value(arg) : value);
  return { short: apply(entry.short), long: apply(entry.long) };
}

