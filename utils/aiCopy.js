/** `{ad}` yer tutucularını doldurur; eksik değer boş kalır. */
export function fillCopy(template, values = {}) {
  return String(template ?? "").replace(/\{(\w+)\}/g, (_, key) =>
    values[key] != null ? String(values[key]) : "",
  );
}
